test("story planning and Script Director review an existing prop through the same editor", async ({ page }) => {
  const project = starterProject();
  const scene = project.scenes[0];
  project.idea = "A cartoon about taking care of books.";
  const actor = project.characters.find(item => item.id === scene.elements[0].characterId)!;
  scene.action = `${actor.name} picks up a book.`;
  project.scenes[0] = addStoryProp(project, scene, "book");
  await restore(page, project);
  await button(page, "Write My Episode Script").click();
  const suggestion = button(page, "Review interaction suggestion: Pick It Up");
  await suggestion.click();
  const studio = page.getByRole("dialog", { name: title });
  await studio.getByRole("button", { name: "Add story prop", exact: true }).click();
  await studio.getByRole("button", { name: "Preview", exact: true }).click();
  await studio.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "Write My Episode Script" })).toBeVisible();
  await button(page, "Close dialog").click();
  expect((await backup(page)).data.scenes[0].interactions).toBeUndefined();
  await button(page, "Review animation suggestions").click();
  await suggestion.click();
  await studio.getByRole("button", { name: "Add story prop", exact: true }).click();
  await studio.getByRole("button", { name: "Preview", exact: true }).click();
  await studio.getByRole("button", { name: "Apply", exact: true }).click();
  await expect(studio).toBeHidden();
  await page.getByRole("button", { name: /^Apply reviewed suggestions/ }).click();
  await expect(page.getByRole("dialog")).toBeHidden();
  const planned = (await backup(page)).data.scenes[0];
  expect(planned.interactions?.[0].kind).toBe("pickup");
  expect(planned.elements.filter(item => item.prop === "book")).toHaveLength(1);
});
