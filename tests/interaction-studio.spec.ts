test.use({ actionTimeout: 12_000 });

const title = "Make My Character Do Something";
const button = (page: Page, name: string) => page.getByRole("button", { name, exact: true });
async function openStudio(page: Page) {
  const tab = button(page, "Edit scene");
  if (await tab.isVisible()) await tab.click();
  await button(page, title).click();
  return page.getByRole("dialog", { name: title });
}
async function showPreviewTab(page: Page) {
  const tab = button(page, "Preview");
  if (await tab.isVisible()) await tab.click();
}
async function downloadEpisode(page: Page) {
  const pending = page.waitForEvent("download");
  await button(page, "Project backup").click();
  const download = await pending;
  expect(download.suggestedFilename()).toMatch(/\.ctepisode$/);
  return (await download.path())!;
}

test("review, carry, release, edit and reopen an interaction with no accidental changes", async ({ page }, info) => {
  test.setTimeout(75_000);
  const project = starterProject();
  project.title = "Put the toy away";
  const actor = project.scenes[0].elements[0];
  actor.animation = undefined;
  actor.motion = "still";
  project.scenes[0].elements = project.scenes[0].elements.filter(item => item.prop !== "toy");
  await restore(page, project);
  await saved(page);
  if (info.project.name === "phone") await button(page, "Switch to dark theme").click();
  const before = (await backup(page)).data;
  let dialog = await openStudio(page);
  await dialog.getByLabel("Original story prop").selectOption("toy");
  await dialog.getByRole("button", { name: "Add story prop", exact: true }).click();
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
  expect((await backup(page)).data.scenes).toEqual(before.scenes);
  dialog = await openStudio(page);
  await dialog.getByLabel("Original story prop").selectOption("toy");
  await dialog.getByRole("button", { name: "Add story prop", exact: true }).click();
  await dialog.getByLabel("Interaction", { exact: true }).selectOption("carry");
  await dialog.getByLabel("Set the object down at a chosen spot").check();
  await number(page, "Release X", "540");
  await number(page, "Release Y", "355");
  await expect(dialog.getByRole("button", { name: "Apply", exact: true })).toBeDisabled();
  await dialog.getByRole("button", { name: "Preview", exact: true }).click();
  await expect(dialog.locator("svg [data-held-by]")).toHaveCount(1);
  await dialog.getByRole("button", { name: "Compare current scene", exact: true }).click();
  await expect(dialog.locator("svg [data-held-by]")).toHaveCount(0);
  await dialog.getByRole("button", { name: "Show proposed scene", exact: true }).click();
  expect((await new AxeBuilder({ page }).include("dialog")
    .withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  const width = await dialog.evaluate(element => ({ scroll: element.scrollWidth, client: element.clientWidth }));
  expect(width.scroll).toBeLessThanOrEqual(width.client + 1);
  await dialog.getByRole("button", { name: "Apply", exact: true }).click();
  await expect(dialog).toBeHidden();
  const applied = (await backup(page)).data;
  const action = applied.scenes[0].interactions![0];
  expect(action.release?.position).toEqual({ x: 540, y: 355 });
  expect(applied.scenes[0].elements.filter(item => item.prop === "toy")).toHaveLength(1);
  expect(applied.scenes[0].elements.find(item => item.id === action.actorId)?.animation?.keyframes.length).toBeGreaterThan(1);
  await button(page, "Undo edit").click();
  expect((await backup(page)).data.scenes).toEqual(before.scenes);
  await button(page, "Redo edit").click();
  await showPreviewTab(page);
  await page.getByRole("button", { name: /Carry It Attach at/ }).click();
  await number(page, "Attach", "0.65");
  await dialog.getByRole("button", { name: "Preview", exact: true }).click();
  await dialog.getByRole("button", { name: "Apply", exact: true }).click();
  await saved(page);
  await page.reload();
  await page.getByRole("button", { name: "Continue Put the toy away" }).click();
  await showPreviewTab(page);
  await expect(page.getByRole("button", { name: "Carry It Attach at 0.65 seconds" })).toBeVisible();
  expect((await backup(page)).data.scenes[0].interactions?.[0].attach).toBe(0.65);
});

test("converts only the scene's can and hands a book to another character", async ({ page }, info) => {
  test.setTimeout(70_000);
  const project = gardenInteractionDemo();
  const scene = project.scenes[0];
  scene.interactions = undefined;
  scene.elements.find(item => item.prop === "watering-can")!.sceneryDepth = "alongside";
  const music = builtInSound("melody");
  project.audioAssets = [music];
  project.audioClips = [newAudioClip(project, music, "music", 0)];
  await restore(page, project);
  if (info.project.name === "phone") await button(page, "Switch to dark theme").click();
  const dialog = await openStudio(page);
  await dialog.getByLabel("Choose Object").selectOption({ label: "Watering can · 1 (scenery)" });
  await expect(dialog.getByRole("button", { name: "Preview", exact: true })).toBeDisabled();
  await dialog.getByRole("button", { name: "Use this scene copy as a story prop", exact: true }).click();
  await expect(dialog.getByRole("button", { name: "Preview", exact: true })).toBeEnabled();
  await dialog.getByLabel("Original story prop").selectOption("book");
  await dialog.getByRole("button", { name: "Add story prop", exact: true }).click();
  await dialog.getByLabel("Interaction", { exact: true }).selectOption("give");
  await dialog.getByRole("button", { name: "Preview", exact: true }).click();
  await expect(dialog.locator("[data-held-by]")).toHaveCount(1);
  const giver = await dialog.locator("[data-held-by]").getAttribute("data-held-by");
  const time = dialog.getByRole("spinbutton", { name: "Preview time (seconds)", exact: true });
  await time.fill("3");
  await expect(dialog.locator("[data-held-by]")).toHaveCount(1);
  expect(await dialog.locator("[data-held-by]").getAttribute("data-held-by")).not.toBe(giver);
  await time.fill("3.9");
  await expect(dialog.locator("[data-held-by]")).toHaveCount(0);
  await time.fill("2.9");
  await dialog.locator(".interaction-review").scrollIntoViewIfNeeded();
  const screenshot = info.outputPath("interaction-handoff.png");
  await page.screenshot({ path: screenshot, animations: "disabled" });
  await info.attach("reviewed book handoff", { path: screenshot, contentType: "image/png" });
  await dialog.getByRole("button", { name: "Apply", exact: true }).click();
  await expect(dialog).toBeHidden();
  await saved(page);
  const original = (await backup(page)).data;
  await voices(page);
  await button(page, "Enable long-episode audio").click();
  await expect(page.getByRole("heading", { name: "Long-episode audio is enabled" })).toBeVisible();
  await button(page, "Back to cartoon").click();
  await saved(page);
  const path = await downloadEpisode(page);
  await page.goto("./");
  await page.getByLabel("Restore project backup file").setInputFiles(path);
  await expect(page.locator(".editor")).toBeVisible();
  const bytes = await readFile(await downloadEpisode(page));
  const restored = (JSON.parse(bytes.subarray(16, 16 + bytes.readUInt32LE(8)).toString("utf8")) as { project: Project }).project;
  expect(restored.id).not.toBe(original.id);
  expect(restored.scenes).toEqual(original.scenes);
  expect(restored.audioAssets[0].file?.sha256).toMatch(/^[a-f0-9]{64}$/);
});

