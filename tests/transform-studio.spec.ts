test.use({ actionTimeout: 12_000 });
const title = "Show How Something Changes";
const button = (page: Page, name: string) => page.getByRole("button", { name, exact: true });
const modal = (page: Page) => page.getByRole("dialog", { name: title });
async function edit(page: Page) {
  const tab = button(page, "Edit scene");
  if (await tab.isVisible()) await tab.click();
  await button(page, title).click();
  return modal(page);
}
async function previewTab(page: Page) {
  const tab = button(page, "Preview");
  if (await tab.isVisible()) await tab.click();
}
async function openExamples(page: Page) {
  await page.getByText("Try a Fix, Build & Transform example", { exact: true }).click();
}

test("review a held wagon change, edit its timing, undo and reopen", async ({ page }, info) => {
  test.setTimeout(80_000);
  const project = transformExample("wagon");
  const scene = project.scenes[0];
  const object = scene.elements.find(item => item.prop === "toy-wagon")!;
  scene.objectTracks = undefined;
  scene.learningSteps = undefined;
  await restore(page, project);
  await saved(page);
  if (info.project.name === "phone") await button(page, "Switch to dark theme").click();
  const original = (await backup(page)).data;
  let dialog = await edit(page);
  await dialog.getByLabel("Choose an Object", { exact: true }).selectOption(object.id);
  await dialog.getByText("Manage named appearances", { exact: true }).click();
  await dialog.getByLabel("Appearance name", { exact: true }).fill("A different draft");
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
  expect((await backup(page)).data.scenes).toEqual(original.scenes);
  dialog = await edit(page);
  await dialog.getByLabel("Choose an Object", { exact: true }).selectOption(object.id);
  await dialog.getByText("Manage named appearances", { exact: true }).click();
  await dialog.getByLabel("Appearance name", { exact: true }).fill("Ready to roll");
  await dialog.getByText("Manage named appearances", { exact: true }).click();
  await dialog.getByLabel("Link to a character action").selectOption({ label: "Put It Down · Attach at 4.65 s" });
  await dialog.getByLabel("Transition").selectOption("reveal");
  await expect(dialog.getByRole("button", { name: "Apply", exact: true })).toBeDisabled();
  await dialog.getByRole("button", { name: "Preview the Change", exact: true }).press("Enter");
  const stage = dialog.getByRole("region", { name: "Proposed scene preview" });
  const wagon = stage.locator(`[data-element-id="${object.id}"]`);
  const time = stage.getByRole("spinbutton", { name: "Preview time (seconds)", exact: true });
  await time.fill("4.45");
  await expect(wagon).toHaveAttribute("data-prop-appearance", "loose-wheel");
  await time.fill("4.82");
  await expect(wagon).toHaveCount(1);
  await expect(wagon).toHaveAttribute("data-held-by", scene.interactions![1].actorId);
  await expect(wagon).toHaveAttribute("data-object-state", "Ready to roll");
  await expect(wagon.locator("clipPath")).toHaveCount(1);
  await time.fill("6");
  await expect(wagon).toHaveAttribute("data-prop-appearance", "fixed-wheel");
  await expect(wagon.locator("clipPath")).toHaveCount(0);
  await dialog.getByRole("button", { name: "Compare current scene", exact: true }).click();
  await expect(wagon).not.toHaveAttribute("data-object-state");
  await dialog.getByRole("button", { name: "Show proposed change", exact: true }).click();
  const size = await dialog.evaluate(element => ({ client: element.clientWidth, scroll: element.scrollWidth }));
  expect(size.scroll).toBeLessThanOrEqual(size.client + 1);
  expect((await new AxeBuilder({ page }).include("dialog").withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await time.fill("9.6");
  await dialog.locator(".interaction-review").scrollIntoViewIfNeeded();
  const screenshot = info.outputPath("transform-review.png");
  await page.screenshot({ path: screenshot, animations: "disabled" });
  await info.attach("object appearance review", { path: screenshot, contentType: "image/png" });
  await dialog.getByRole("button", { name: "Apply", exact: true }).click();
  await expect(dialog).toBeHidden();
  const applied = (await backup(page)).data;
  const first = applied.scenes[0].objectTracks![0];
  expect(first.objectId).toBe(object.id);
  expect(first.changes[0].cue?.interactionId).toBe(scene.interactions![1].id);
  expect(applied.scenes[0].elements).toEqual(original.scenes[0].elements);
  await button(page, "Undo edit").click();
  expect((await backup(page)).data.scenes).toEqual(original.scenes);
  await button(page, "Redo edit").click();
  await previewTab(page);
  await button(page, "Change Toy wagon to Ready to roll at 4.65 seconds").click();
  await modal(page).getByLabel("Link to a character action").selectOption("");
  await number(page, "Change at This Time (seconds)", "8.4");
  await modal(page).getByRole("button", { name: "Preview the Change", exact: true }).click();
  await modal(page).getByRole("button", { name: "Apply", exact: true }).click();
  await saved(page);
  await page.reload();
  await button(page, `Continue ${project.title}`).click();
  await previewTab(page);
  await expect(button(page, "Change Toy wagon to Ready to roll at 8.40 seconds")).toBeVisible();
  const reopened = (await backup(page)).data.scenes[0].objectTracks![0];
  expect(reopened.states).toEqual(first.states);
  expect(reopened.changes[0]).toMatchObject({ id: first.changes[0].id, at: 8.4 });
  await button(page, "Change Toy wagon to Ready to roll at 8.40 seconds").click();
  await modal(page).getByRole("button", { name: "Restore the original object", exact: true }).click();
  await modal(page).getByRole("button", { name: "Restore object artwork", exact: true }).click();
  expect((await backup(page)).data.scenes[0].objectTracks).toEqual([]);
  await button(page, "Undo edit").click();
  expect((await backup(page)).data.scenes[0].objectTracks?.[0]).toEqual(reopened);
});

test("edits a drawing copy and reuses that appearance from the existing library", async ({ page }) => {
  test.setTimeout(70_000);
  const source = { id: uid(), type: "image" as const, name: "Original drawing", mime: "image/png" as const, dataUrl: pixel, drawing: blankDrawing() };
  const project = placeLibraryItem(starterProject(), 0, imageLibraryItem(source, "My picture", "drawing"));
  const object = project.scenes[0].elements.at(-1)!;
  await restore(page, project);
  let dialog = await edit(page);
  await dialog.getByLabel("Choose an Object", { exact: true }).selectOption(object.id);
  await dialog.getByText("Manage named appearances", { exact: true }).click();
  await dialog.getByRole("button", { name: "Edit a copy of the artwork", exact: true }).click();
  const drawing = page.getByRole("dialog");
  const canvas = drawing.locator("canvas");
  await expect(canvas).toBeVisible();
  await canvas.scrollIntoViewIfNeeded();
  const bounds = (await canvas.boundingBox())!;
  await page.mouse.move(bounds.x + bounds.width * 0.35, bounds.y + bounds.height * 0.35);
  await page.mouse.down();
  await page.mouse.move(bounds.x + bounds.width * 0.58, bounds.y + bounds.height * 0.48, { steps: 9 });
  await page.mouse.up();
  await drawing.getByRole("button", { name: "Use drawing as this appearance", exact: true }).click();
  dialog = modal(page);
  await dialog.getByText("Manage named appearances", { exact: true }).click();
  await dialog.getByLabel("Appearance name", { exact: true }).fill("My finished drawing");
  await dialog.getByRole("button", { name: "Save appearance to Art Library", exact: true }).click();
  await expect(dialog.getByRole("status").filter({ hasText: "Saved My finished drawing" })).toBeVisible();
  await dialog.getByRole("button", { name: "Choose artwork from my library", exact: true }).click();
  await button(page, "Drawings").click();
  const card = page.locator(".library-card").filter({ has: page.getByRole("heading", { name: "My finished drawing", exact: true }) });
  await card.getByRole("button", { name: "Choose this artwork", exact: true }).click();
  await number(page, "Change at This Time (seconds)", "2");
  await dialog.getByRole("button", { name: "Preview the Change", exact: true }).click();
  await dialog.getByRole("button", { name: "Apply", exact: true }).click();
  const result = (await backup(page)).data;
  expect(result.assets.find(asset => asset.id === object.assetId)).toEqual(project.assets[0]);
  const state = result.scenes[0].objectTracks![0].states[1];
  expect(state.art.kind).toBe("image");
  const image = result.assets.find(asset => asset.id === (state.art.kind === "image" && state.art.assetId))!;
  expect(image.drawing?.objects.length).toBeGreaterThan(0);
  expect(image.dataUrl).not.toBe(project.assets[0].dataUrl);
  expect(result.assets).toHaveLength(2);
});

test("links a new teaching step to the actual wagon repair and a spoken line", async ({ page }) => {
  test.setTimeout(70_000);
  await page.goto("./");
  await openExamples(page);
  await button(page, `Try ${EXAMPLE_NAMES.wagon}`).click();
  await expect(page.locator(".editor")).toBeVisible();
  await button(page, "Write My Episode Script").click();
  const dialog = page.getByRole("dialog", { name: "Write My Episode Script" });
  await dialog.getByText("Teach It Step by Step", { exact: true }).click();
  await dialog.getByRole("button", { name: "Add learning step", exact: true }).click();
  await dialog.getByLabel("What will viewers learn?").fill("Ask for help and watch the wheel.");
  await dialog.getByLabel("What will viewers see?", { exact: true }).selectOption({ label: "Toy wagon → Wheel attached · 9.25 s" });
  const line = dialog.getByLabel("Instructional script line", { exact: true });
  await line.selectOption({ label: "4. Hold it steady. I will press the wheel into place." });
  const lineId = await line.inputValue();
  await dialog.getByRole("button", { name: "Check this moment in the scene", exact: true }).click();
  await expect(dialog.getByRole("region", { name: "Proposed scene preview" }).locator('[data-prop-appearance="fixed-wheel"]')).toHaveAttribute("data-held-by", /.+/);
  await dialog.getByRole("button", { name: "Apply learning steps", exact: true }).click();
  await expect(dialog.getByRole("status").filter({ hasText: "Learning steps saved." })).toBeVisible();
  await dialog.getByRole("button", { name: "Close dialog", exact: true }).click();
  const project = (await backup(page)).data;
  expect(project.scenes[0].learningSteps!.at(-1)).toMatchObject({ lineId, at: 9.25, cue: { kind: "change" } });
  expect(project.scenes[0].script!.lines.find(item => item.id === lineId)?.clipId).toBeTruthy();
});

test("the three short examples open as editable scenes with timed original changes", async ({ page }) => {
  test.setTimeout(75_000);
  await page.goto("./");
  for (const [name, prop] of [[EXAMPLE_NAMES.tidy, "table"], [EXAMPLE_NAMES.seed, "flower-pot"], [EXAMPLE_NAMES.bridge, "paper-bridge"]] as const) {
    await openExamples(page);
    await button(page, `Try ${name}`).click();
    await expect(page.getByRole("heading", { name, exact: true }).first()).toBeVisible();
    const sample = (await backup(page)).data;
    const scene = sample.scenes[0];
    const track = scene.objectTracks![0];
    expect(track.changes.length).toBeGreaterThan(0);
    expect(scene.elements.find(item => item.id === track.objectId)?.prop).toBe(prop);
    if (prop === "flower-pot") expect(sample.captions.some(caption => caption.text.includes("Weeks later"))).toBe(true);
    await button(page, "Save and return to my cartoons").click();
    await expect(page.locator(".dashboard")).toBeVisible();
  }
});
